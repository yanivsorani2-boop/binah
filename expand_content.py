FAQ_SCHEMA_TEMPLATE = """  <script type="application/ld+json">
  {{
    "@context": "https://schema.org",
    "@type": "FAQPage",
    "mainEntity": [{entries}
    ]
  }}
  </script>"""

FAQ_ENTRY_TEMPLATE = """
      {{
        "@type": "Question",
        "name": "{q}",
        "acceptedAnswer": {{
          "@type": "Answer",
          "text": "{a}"
        }}
      }}"""

FAQ_HTML_TEMPLATE = """
      <div class="faq-section" style="margin-top:40px">
        <h2 style="font-size:1.2rem;font-weight:700;margin-bottom:20px;border-right:3px solid var(--accent);padding-right:12px">{title}</h2>
        <div class="faq-list" itemscope itemtype="https://schema.org/FAQPage">
{items}
        </div>
      </div>"""

FAQ_ITEM_HTML = """          <div class="faq-item" style="margin-bottom:20px;padding:16px;background:var(--bg-card);border:1px solid var(--border);border-radius:10px" itemscope itemprop="mainEntity" itemtype="https://schema.org/Question">
            <h3 style="font-size:1rem;font-weight:700;margin-bottom:8px" itemprop="name">{q}</h3>
            <div style="font-size:0.93rem;line-height:1.8;color:var(--text-secondary)" itemscope itemprop="acceptedAnswer" itemtype="https://schema.org/Answer">
              <span itemprop="text">{a}</span>
            </div>
          </div>"""


def build_faq_html(faq):
    items_html = "\n".join(
        FAQ_ITEM_HTML.format(q=item["q"], a=item["a"])
        for item in faq["items"]
    )
    return FAQ_HTML_TEMPLATE.format(title=faq["title"], items=items_html)


def build_faq_schema(faq):
    entries = ",".join(
        FAQ_ENTRY_TEMPLATE.format(
            q=item["q"].replace('"', '\\"'),
            a=item["a"].replace('"', '\\"')
        )
        for item in faq["items"]
    )
    return FAQ_SCHEMA_TEMPLATE.format(entries=entries)


def add_faq_to_article(filepath, faq):
    html = filepath.read_text(encoding="utf-8")
    changed = False

    # הוסף FAQ schema ל-<head> (אם לא קיים FAQPage)
    if '"FAQPage"' not in html:
        schema = build_faq_schema(faq)
        html = html.replace("</head>", f"{schema}\n</head>", 1)
        changed = True

    # הוסף FAQ HTML לפני </main>
    if 'class="faq-section"' not in html:
        faq_html = build_faq_html(faq)
        # נסה לשים לפני article-tags
        if '<div class="article-tags"' in html:
            html = html.replace(
                '<div class="article-tags"',
                f'{faq_html}\n      <div class="article-tags"',
                1
            )
        else:
            html = html.replace("</main>", f"{faq_html}\n    </main>", 1)
        changed = True

    if changed:
        filepath.write_text(html, encoding="utf-8")
        print(f"  ✅ FAQ הוסף: {filepath.name}")
    return changed


def add_noindex(filepath):
    html = filepath.read_text(encoding="utf-8")
    if 'name="robots"' in html:
        # שנה ל-noindex
        html = re.sub(
            r'<meta\s+name="robots"\s+content="[^"]*"',
            '<meta name="robots" content="noindex, follow"',
            html
        )
    else:
        html = html.replace(
            "</head>",
            '  <meta name="robots" content="noindex, follow">\n</head>',
            1
        )
    filepath.write_text(html, encoding="utf-8")
    print(f"  🚫 noindex: {filepath.name}")


def update_sitemap():
    sitemap_path = BASE / "sitemap.xml"
    content = sitemap_path.read_text(encoding="utf-8")

    # הסר שורות עם 2026-03-18 articles
    lines = content.split("\n")
    new_lines = []
    skip_next = 0
    for line in lines:
        if any(slug in line for slug in [
            "articles/2026-03-18-",
            "articles/2026-03-19-ai-agents-enterprise-2026.html"
        ]):
            skip_next = 0  # skip the <url>...</url> block
            continue
        new_lines.append(line)

    content = "\n".join(new_lines)

    # הסר בלוקי <url> שלמים של כפולות
    content = re.sub(
        r'\s*<url>\s*<loc>https://binah\.co\.il/articles/2026-03-18-[^<]*</loc>.*?</url>',
        '',
        content,
        flags=re.DOTALL
    )
    content = re.sub(
        r'\s*<url>\s*<loc>https://binah\.co\.il/articles/2026-03-19-ai-agents-enterprise-2026\.html</loc>.*?</url>',
        '',
        content,
        flags=re.DOTALL
    )

    # עדכן lastmod לכל ה-articles
    content = re.sub(
        r'<lastmod>2026-03-\d+</lastmod>',
        '<lastmod>2026-04-22</lastmod>',
        content
    )

    # הוסף about.html ו-methodology.html אם לא קיים
    if "about.html" not in content:
        about_entry = """
  <url><loc>https://binah.co.il/about.html</loc><changefreq>monthly</changefreq><priority>0.7</priority><lastmod>2026-04-22</lastmod></url>
  <url><loc>https://binah.co.il/methodology.html</loc><changefreq>monthly</changefreq><priority>0.6</priority><lastmod>2026-04-22</lastmod></url>"""
        content = content.replace(
            "  <!-- Articles -->",
            f"{about_entry}\n\n  <!-- Articles -->"
        )

    sitemap_path.write_text(content, encoding="utf-8")
    print("  ✅ sitemap.xml עודכן")


